#!/usr/bin/env python3
"""
Module that provides a function to calculate the floor of a float number.
"""
import math


def floor(n: float) -> int:
    """
    Return the floor of the given floating-point number as an integer.

    Args:
        n (float): The floating-point number.

    Returns:
        int: The floor of the float.
    """
    return math.floor(n)
